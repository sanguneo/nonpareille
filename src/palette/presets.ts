export function getPreset(name: string): Palette {
  const colors = PRESETS[name.toLowerCase()];
  if (!colors) throw new InputError(`Unknown palette preset "${name}". Available: ${Object.keys(PRESETS).join(", ")}`);
  return createPalette(colors);
}
